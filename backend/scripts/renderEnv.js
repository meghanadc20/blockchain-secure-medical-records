'use strict';
/**
 * Writes `.env.render` (git-ignored) in the project root: the environment variables for the
 * public Render deployment, built from your local .env. Upload it in the Render dashboard with
 * Environment → "Add from .env" so no secret ever has to be copied into chat or into GitHub.
 * Values are never printed — only the variable names.
 *
 *   npm run render:env
 *
 * Differences from local development:
 *   - NODE_ENV=production; PORT is left out (Render sets it).
 *   - MONGO_DB_NAME = DEMO_MONGO_DB_NAME (default "medchain_demo"): a SEPARATE database on the
 *     same Atlas cluster, so your existing local data is never touched.
 *   - Blockchain = Sepolia: SEPOLIA_RPC_URL / SEPOLIA_CONTRACT_ADDRESS / SEPOLIA_PRIVATE_KEY.
 *   - A separate production JWT secret (generated once, kept in .env as RENDER_JWT_SECRET).
 *   - Local-only values (GANACHE_MNEMONIC, GITHUB_TOKEN, ADMIN_*) are NOT included.
 */
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const { readEnvValue, setEnvValue } = require('./chain/envFile');

const OUT = path.resolve(__dirname, '../../.env.render');
const need = (key, hint) => {
  const v = readEnvValue(key);
  if (!v) throw new Error(`${key} is missing in .env. ${hint || ''}`.trim());
  return v;
};

try {
  let jwt = readEnvValue('RENDER_JWT_SECRET');
  if (!jwt) { jwt = crypto.randomBytes(48).toString('hex'); setEnvValue('RENDER_JWT_SECRET', jwt); }

  const vars = {
    NODE_ENV: 'production',
    NODE_VERSION: '22',
    MONGO_URI: need('MONGO_URI'),
    MONGO_DB_NAME: readEnvValue('DEMO_MONGO_DB_NAME') || 'medchain_demo',
    JWT_SECRET: jwt,
    JWT_EXPIRES_IN: readEnvValue('JWT_EXPIRES_IN') || '1h',
    SUPABASE_URL: need('SUPABASE_URL'),
    SUPABASE_ANON_KEY: readEnvValue('SUPABASE_ANON_KEY'),
    SUPABASE_SERVICE_ROLE_KEY: need('SUPABASE_SERVICE_ROLE_KEY'),
    SUPABASE_BUCKET: readEnvValue('SUPABASE_BUCKET') || 'medical-records',
    FILE_ENCRYPTION_KEY: need('FILE_ENCRYPTION_KEY'),
    BLOCKCHAIN_RPC_URL: need('SEPOLIA_RPC_URL', 'Add your free Alchemy Sepolia URL.'),
    CHAIN_ID: '11155111',
    CONTRACT_ADDRESS: need('SEPOLIA_CONTRACT_ADDRESS', 'Run npm run chain:deploy:sepolia first.'),
    PRIVATE_KEY: need('SEPOLIA_PRIVATE_KEY', 'Run npm run chain:sepolia-wallet first.'),
    TESTNET_WALLET_FUNDING_ETH: readEnvValue('TESTNET_WALLET_FUNDING_ETH') || '0.005',
    CORS_ORIGIN: readEnvValue('RENDER_URL'),
  };
  const lines = ['# Generated by `npm run render:env` — SECRET. Never commit or share this file.'];
  for (const [k, v] of Object.entries(vars)) if (v) lines.push(`${k}=${v}`);
  fs.writeFileSync(OUT, `${lines.join('\n')}\n`, { mode: 0o600 });
  console.log(`Wrote .env.render with: ${Object.keys(vars).filter((k) => vars[k]).join(', ')}`);
  if (!vars.CORS_ORIGIN) console.log('Tip: after Render gives you a URL, set RENDER_URL in .env and run this again (optional).');
} catch (e) {
  console.error('Could not build .env.render:', e.message);
  process.exit(1);
}
